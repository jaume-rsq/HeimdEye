    Els valors es desen xifrats i no es tornen a mostrar. El codi només rep els secrets que esmenta:
    en bash, <code>HE_SECRET_&lt;NOM&gt;</code> (valor) o <code>HE_SECRET_&lt;NOM&gt;_USER</code>, <code>_PASSWORD</code>,
    <code>_KEY_FILE</code>, <code>_PUBKEY</code>; a Ansible, <code>&lt;nom&gt;</code> o <code>&lt;nom&gt;.user</code>,
    <code>.password</code>, <code>.key_file</code>, <code>.pubkey</code>. A la sortida surten com a <code>********</code>.
    Un d'usuari i contrasenya o una clau SSH també poden ser l'accés d'un mòdul o d'un tipus d'equip.
